def characters():
    return sorted({character for word in synthetic.WORDS for character in word})


def build_tiny_bert(path):
    """A BERT with 2 small layers and a fast WordPiece tokenizer.

    Three words are split into two word pieces, to exercise the alignment between the
    sub-tokens and the labels of the words.
    """
    from tokenizers import Tokenizer, models, pre_tokenizers, processors
    from transformers import BertConfig, BertModel, PreTrainedTokenizerFast

    word_pieces = {
        "thoracique": ["thor", "##acique"],
        "traitement": ["trait", "##ement"],
        "dyspnée": ["dys", "##pnée"],
    }
    tokens = ["[PAD]", "[UNK]", "[CLS]", "[SEP]", "[MASK]"]
    for word in synthetic.WORDS:
        tokens.extend(piece for piece in word_pieces.get(word, [word]) if piece not in tokens)
    vocab = {token: index for index, token in enumerate(tokens)}

    tokenizer = Tokenizer(models.WordPiece(vocab=vocab, unk_token="[UNK]"))
    tokenizer.pre_tokenizer = pre_tokenizers.Whitespace()
    tokenizer.post_processor = processors.TemplateProcessing(
        single="[CLS] $A [SEP]",
        pair="[CLS] $A [SEP] $B:1 [SEP]:1",
        special_tokens=[("[CLS]", vocab["[CLS]"]), ("[SEP]", vocab["[SEP]"])],
    )
    PreTrainedTokenizerFast(
        tokenizer_object=tokenizer,
        unk_token="[UNK]",
        pad_token="[PAD]",
        cls_token="[CLS]",
        sep_token="[SEP]",
        mask_token="[MASK]",
        model_max_length=512,
    ).save_pretrained(path)

    config = BertConfig(
        vocab_size=len(vocab),
        hidden_size=32,
        num_hidden_layers=2,
        num_attention_heads=2,
        intermediate_size=64,
        max_position_embeddings=512,
    )
    BertModel(config).save_pretrained(path)


def build_tiny_flaubert(path):
    """A FlauBERT with 2 small layers and its slow BPE tokenizer.

    The tokenizer has no merge rule: every word is split into its characters. The
    training scripts have a specific code path for the models whose name contains
    "flaubert", because this tokenizer cannot align sub-tokens and words by itself.
    """
    from transformers import FlaubertConfig, FlaubertModel, FlaubertTokenizer

    path.mkdir(parents=True)
    tokens = ["<s>", "</s>", "<pad>", "<unk>"] + [f"<special{i}>" for i in range(10)]
    for character in characters():
        tokens += [character, f"{character}</w>"]
    vocab_file = path / "vocab.json"
    vocab_file.write_text(json.dumps({token: index for index, token in enumerate(tokens)}), encoding="utf-8")
    merges_file = path / "merges.txt"
    merges_file.write_text("", encoding="utf-8")

    FlaubertTokenizer(str(vocab_file), str(merges_file), model_max_length=512).save_pretrained(path)
    config = FlaubertConfig(vocab_size=len(tokens), emb_dim=32, n_layers=2, n_heads=2, max_position_embeddings=512)
    FlaubertModel(config).save_pretrained(path)


