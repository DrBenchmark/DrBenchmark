class RecipeFailure(Exception):
    """A recipe did not run to the end.

    This is not an `AssertionError`, so that a crash is never mistaken for the expected
    failure of a test marked with `xfail(raises=AssertionError)`.
    """


class RecipeRun:
    """Outcome of one run of a recipe."""

    def __init__(self, task, completed, directory):
        self.task = task
        self.returncode = completed.returncode
        self.log = completed.stdout + completed.stderr
        self.directory = directory

    @property
    def run_files(self):
        return sorted((self.directory / "runs").glob("*.json"))

    @property
    def result(self):
        """Content of the JSON file written by the run."""
        self.check()
        return read_json(self.run_files[0])

    def check(self):
        if self.returncode != 0:
            raise RecipeFailure(f"{self.task.name} failed:\n{self.log[-3000:]}")
        if len(self.run_files) != 1:
            raise RecipeFailure(f"{self.task.name} wrote {len(self.run_files)} result files instead of 1")


@pytest.fixture(scope="session")
def run_recipe(tmp_path_factory, synthetic_data):
    """Run a task as `run.py` does, on the synthetic data, and return a `RecipeRun`.

    The launcher of the task is called from its `scripts/` directory, with one epoch
    and a fixed seed. The models and the results are written in a temporary directory.
    The offline mode is forced, whatever `config.yaml` says, so that the recipe reads
    the synthetic data instead of downloading the real ones.
    Identical runs are only executed once per test session.
    """
    cache = {}

    def run(task_name, model, *extra_args):
        key = (task_name, str(model), extra_args)
        if key not in cache:
            task = Task(task_name)
            directory = tmp_path_factory.mktemp(task_name)
            # The scripts create the directory of the models, not the one of the results
            (directory / "runs").mkdir()
            arguments = [
                "--data_dir", f"{synthetic_data / task.recipe}/",
                "--output_dir", f"{directory / 'save_models'}/",
                "--run_dir", f"{directory / 'runs'}/",
                "--offline", "True",
                "--seed", "0",
                "--epochs", "1",
                *extra_args,
            ]
            command = task.command(model) + " " + " ".join(shlex.quote(str(argument)) for argument in arguments)
            completed = run_command(command, cwd=task.scripts_dir)
            cache[key] = RecipeRun(task, completed, directory)
        return cache[key]

    return run
